// skeeball/tools/build-trajectory-map.mjs - rebuilds skeeball/trajectory-map.json, the precomputed
// grid behind skeeball/trajectory.html.
//
// The page simulates the ONE throw you have selected live, which is fast. The map behind it is
// every combination at once - 55 angles x 51 powers - which is minutes of physics, so it is
// computed here and shipped as data.
//
// It runs the REAL engine (skeeball/js/machines/brickcity/), so the map cannot drift from the game
// by construction. RE-RUN IT after any change to that machine's physics, geometry or geom block,
// or the page will confidently show you last week's machine.
//
// `banks` (2026-09-03, Matt: "mark the banked cells on the map differently from the clean ones, so
// you can see at a glance which 100s are skill and which are luck"): per cell, did the ball touch a
// SIDE RAIL or the BACK WALL before the capture that scored it? 39 of the 77 hundreds - 51% - are
// banks, which is why the 100 read as scattered luck: the aimed shot underneath is a clean,
// SYMMETRIC band (+1.0 to +6.5 deg on the right, -6.5 to -1.5 on the left, 19 cells each side),
// with the bank shots sprayed across everything else.
//
// THE FIRST MAP SHIPPED STALE, WHICH IS WHY THIS FILE EXISTS. It was generated by hand before
// f8a635a ("nothing held a ball in the basket it fell into") landed, so the page confidently drew
// the machine as it had been the day before: 133 of 2805 cells wrong and 65 hundreds where the
// real machine has 77. Run --check after any change to that machine and the drift is caught.
//
//   node skeeball/tools/build-trajectory-map.mjs [--check]
//
// --check rebuilds and compares against the committed file instead of writing it.
import { writeFileSync, readFileSync } from 'node:fs';
import { boardById } from '../js/boards.js';
import { loadEngine, engineFor } from '../js/engines.js';

const A0 = -13.5, A1 = 13.5, DA = 0.5;
const P0 = 0.2, P1 = 1.2, DP = 0.02;
const OUT = new URL('../trajectory-map.json', import.meta.url);

// One letter per outcome. FROZEN - trajectory.html's COLOUR table is keyed on these.
const CODE = { topL: 'L', topR: 'R', topC: 'C', midL: 'l', midR: 'r', midC: 'c',
  lowL: 'x', lowR: 'z', lowC: 'y' };

await loadEngine('brickcity');
const P = engineFor('brickcity').physics;
const board = boardById('brickcity');
const G = board.geom;

/** The page's angle slider is the SERVE angle in degrees; the engine takes -1..1 of geom.aimMax. */
const aimOf = (deg) => Math.max(-1, Math.min(1, (deg * Math.PI / 180) / G.aimMax));

function throwOne(deg, power) {
  const st = P.startThrow(board, { power, aim: aimOf(deg) });
  let n = 0, wallT = 0, capT = 0;
  while (!st.done && n++ < 240 * 14) {
    P.step(board, st, P.STEP);
    for (const e of st.events) {
      if (!wallT && e.type === 'contact' && (e.part === 'rail' || e.part === 'backboard')) wallT = st.t;
      if (!capT && e.type === 'capture') capT = st.t;
    }
    st.events.length = 0;
  }
  const o = st.outcome;
  const code = !o ? '-' : (CODE[o.hole] || '.');
  // A bank is a wall touched BEFORE the ball went in. A wall hit on the way out is not a bank.
  const banked = code !== '.' && code !== '-' && wallT > 0 && capT > 0 && wallT < capT;
  return { code, banked };
}

const cols = Math.round((A1 - A0) / DA) + 1;
const rows = Math.round((P1 - P0) / DP) + 1;
const cells = [];
const banks = [];
const t0 = Date.now();
for (let ri = 0; ri < rows; ri++) {
  for (let ci = 0; ci < cols; ci++) {
    const r = throwOne(+(A0 + ci * DA).toFixed(2), +(P0 + ri * DP).toFixed(3));
    cells.push(r.code);
    banks.push(r.banked ? '1' : '0');
  }
  if (ri % 5 === 0) process.stderr.write(`  row ${ri + 1}/${rows}  ${((Date.now() - t0) / 1000).toFixed(0)}s\n`);
}
const out = { a0: A0, a1: A1, da: DA, p0: P0, p1: P1, dp: DP, cols, rows,
  cells: cells.join(''), banks: banks.join('') };

if (process.argv.includes('--check')) {
  const old = JSON.parse(readFileSync(OUT, 'utf8'));
  const same = old.cells === out.cells;
  console.log(same ? 'ok   cells identical to the committed map' : 'FAIL cells differ from the committed map');
  if (!same) {
    let d = 0;
    for (let i = 0; i < out.cells.length; i++) if (old.cells[i] !== out.cells[i]) d++;
    console.log(`     ${d} of ${out.cells.length} cells changed`);
  }
  process.exit(same ? 0 : 1);
}
writeFileSync(OUT, JSON.stringify(out));
const nb = banks.filter((b) => b === '1').length;
const scoring = cells.filter((c) => c !== '.' && c !== '-').length;
console.log(`wrote ${cols}x${rows} = ${cells.length} cells in ${((Date.now() - t0) / 1000).toFixed(0)}s`);
console.log(`  scoring cells ${scoring}, of which banked off a wall first: ${nb} (${(100 * nb / scoring).toFixed(0)}%)`);
