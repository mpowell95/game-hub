// tools/build-arrow-boards8.mjs - GENERATES way-out/js/boards8.js: Arrow Maze's Hard and Expert levels on
// GENERATOR 8 (2026-10-27). Matt played the admin test boards (since removed): "Holy shit
// these are WAY harder. And WAY better", then on the milder five: "That's perfect for Hard. Make the
// updates". So Hard is that style throughout, and Expert climbs through the three test styles (far
// blockers, mixed, forced order). Same 16x22 grid as the test boards: bigger arrows than today's Hard
// or Expert, harder by how they play. The search (tools/arrow-search.mjs) is too slow for a phone, so
// the boards are built here, once, and shipped packed (~190 bytes a board).
//
// APPEND-ONLY once shipped: a level number names its board, and a saved level, a replay or a logged
// finish must keep meaning the same arrows. Never change a board; add boards at the end, never
// before. way-out/js/test.js pins the file.
//
//   node tools/build-arrow-boards8.mjs [--count 250] [--iters 20000]
import { writeFileSync } from 'node:fs';
import { W, H, measure, search } from './arrow-search.mjs';
const E = await import('../way-out/js/engine.js');
const arg = (k, d) => (process.argv.includes(k) ? +process.argv[process.argv.indexOf(k) + 1] : d);
const COUNT = arg('--count', 250), ITERS = arg('--iters', 20000);   // these defaults built the shipped file

/** Expert's style for its k-th board (0 = level 201): far blockers and mixed first, forced order more
 *  and more often as it climbs. */
export function expertStyle(k) {
  const A = ['far', 'mixed', 'far', 'mixed', 'mixed'];
  const B = ['mixed', 'forced', 'far', 'mixed', 'forced'];
  const C = ['forced', 'mixed', 'forced', 'forced', 'far'];
  return (k < 60 ? A : k < 150 ? B : C)[k % 5];
}

// Packing: 7 bits arrow count; per arrow 9 bits tail cell, 4 bits (length - 1), then 2 bits a step
// (0 right, 1 left, 2 down, 3 up), tail to head. Base64.
const STEP = { 1: 0, [-1]: 1, [W]: 2, [-W]: 3 };
function pack(arrows) {
  const bits = [];
  const put = (v, n) => { for (let k = n - 1; k >= 0; k--) bits.push((v >> k) & 1); };
  put(arrows.length, 7);
  for (const c of arrows) {
    put(c[0], 9); put(c.length - 1, 4);
    for (let k = 1; k < c.length; k++) put(STEP[c[k] - c[k - 1]], 2);
  }
  while (bits.length % 8) bits.push(0);
  const bytes = Buffer.alloc(bits.length / 8);
  for (let i = 0; i < bytes.length; i++) { let v = 0; for (let k = 0; k < 8; k++) v = (v << 1) | bits[i * 8 + k]; bytes[i] = v; }
  return bytes.toString('base64');
}

const out = { hard: [], expert: [] };
for (const band of ['hard', 'expert']) {
  const t0 = Date.now();
  let sum = { n: 0, rounds: 0, dist: 0 };
  for (let k = 0; k < COUNT; k++) {
    const style = band === 'hard' ? 'hard' : expertStyle(k);
    const arrows = search(E.seedOf(`b8-${band}`, k), style, ITERS);
    if (arrows.length > 127 || arrows.some((c) => c.length > 16)) throw new Error('board too big to pack');
    const m = measure(arrows);
    sum.n += m.n; sum.rounds += m.rounds; sum.dist += m.dist;
    const s = pack(arrows);
    const back = E.unpackB8(s);
    if (JSON.stringify(back) !== JSON.stringify(arrows)) throw new Error(`pack round trip failed: ${band} ${k}`);
    out[band].push(s);
    if ((k + 1) % 50 === 0) console.log(`${band} ${k + 1}/${COUNT} (${((Date.now() - t0) / 1000).toFixed(0)} s)`);
  }
  console.log(`${band}: ${COUNT} boards, avg ${(sum.n / COUNT).toFixed(0)} arrows, ${(sum.rounds / COUNT).toFixed(1)} rounds, blocker ${(sum.dist / COUNT).toFixed(1)} dots`);
}
const file = `// way-out/js/boards8.js - GENERATED by tools/build-arrow-boards8.mjs (2026-10-27). NEVER HAND-EDIT.
// Arrow Maze's Hard and Expert boards on generator 8 (${W}x${H}, packed; engine.js unpackB8 / buildB8).
// APPEND-ONLY once shipped: a level number names its board (way-out/js/test.js pins it).
export const B8_W = ${W};
export const B8_H = ${H};
export const B8 = {
  hard: ${JSON.stringify(out.hard)},
  expert: ${JSON.stringify(out.expert)},
};
`;
writeFileSync(new URL('../way-out/js/boards8.js', import.meta.url), file);
console.log(`wrote way-out/js/boards8.js (${(file.length / 1024).toFixed(1)} KB)`);
