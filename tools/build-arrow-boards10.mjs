// tools/build-arrow-boards10.mjs - GENERATES way-out/js/boards10.js: Arrow Maze's Expert on GENERATOR 10
// (2026-10-28). Matt, halfway through Impossible test board 11: "THIS is what Expert should be like." Board
// 11's recipe, on its grid (28x38, the old Expert's largest): exactly one arrow free at every step, the next
// one far from the last (~8-9 dots), most blocked arrows' blockers far off (lookalikes), no trains, ~75
// arrows. Slow (~2-3 min a board), so it runs in parallel parts:
//   node tools/build-arrow-boards10.mjs --part <k> --parts <N> --count <C>   (writes a part file)
//   node tools/build-arrow-boards10.mjs --merge --count <C>                  (writes boards10.js)
// APPEND-ONLY once shipped (way-out/js/test.js pins it): a level number names its board.
import { writeFileSync, readFileSync, existsSync, mkdirSync } from 'node:fs';
import { measure, search, setGrid } from './arrow-search.mjs';
import { styledBoard } from './arrow-styles.mjs';
const E = await import('../way-out/js/engine.js');
const arg = (k, d) => (process.argv.includes(k) ? +process.argv[process.argv.indexOf(k) + 1] : d);
const W = 28, H = 38, COUNT = arg('--count', 100), ITERS = arg('--iters', 1500000);
const OVER = { jump: 26, near: 12, minN: 95, maxN: 160, fill: 0.55, rounds: 4, dist: 9, farS: 40 };   // board 11's
const PARTS_DIR = new URL('../.boards10-parts/', import.meta.url);

// Packing (28x38 needs 11 bits a cell): 7 bits arrow count; per arrow 11 bits tail cell, 5 bits (length - 1),
// then 2 bits a step (0 right, 1 left, 2 down, 3 up), tail to head. Base64. engine.js unpackB10 reads it.
const STEP = { 1: 0, [-1]: 1, [W]: 2, [-W]: 3 };
function pack(arrows) {
  const bits = [];
  const put = (v, n) => { for (let k = n - 1; k >= 0; k--) bits.push((v >> k) & 1); };
  put(arrows.length, 7);
  for (const c of arrows) { put(c[0], 11); put(c.length - 1, 5); for (let k = 1; k < c.length; k++) put(STEP[c[k] - c[k - 1]], 2); }
  while (bits.length % 8) bits.push(0);
  const bytes = Buffer.alloc(bits.length / 8);
  for (let i = 0; i < bytes.length; i++) { let v = 0; for (let k = 0; k < 8; k++) v = (v << 1) | bits[i * 8 + k]; bytes[i] = v; }
  return bytes.toString('base64');
}

/** Board k: the first seed whose search meets the recipe. */
function boardAt(k) {
  // From board 101 (k 100) the styles turn (tools/arrow-styles.mjs, 2026-11-04: Matt, "yes to mixing up board styles").
  if (k >= 100) { const b = styledBoard('expert', k); return { s: pack(b.arrows), style: b.style, m: b.m }; }
  setGrid(W, H);
  for (let s = 0; s < 6; s++) {
    const a = search(E.seedOf(`b10-expert-${k}`, s), 'jumps', ITERS, OVER);
    const m = measure(a);
    if (m && m.n >= 65 && m.n <= 127 && m.rounds === m.n && m.maxFree === 1 && m.trains === 0 && m.jump >= 7.5 && a.every((c) => c.length <= 32)) {
      return { s: pack(a), m: { n: m.n, jump: +m.jump.toFixed(2), dist: +m.dist.toFixed(2) } };
    }
  }
  throw new Error(`board ${k}: no seed met the recipe`);
}

if (process.argv.includes('--merge')) {
  // APPEND-ONLY: the shipped boards are copied as they are; only boards past them come from part files.
  const shipped = await import('../way-out/js/boards10.js');
  const out = shipped.B10.slice(), styles = (shipped.B10_STYLE || shipped.B10.map(() => 'classic')).slice();
  for (let k = out.length; k < COUNT; k++) {
    const f = new URL(`b${k}.json`, PARTS_DIR);
    if (!existsSync(f)) throw new Error(`missing part for board ${k}`);
    const b = JSON.parse(readFileSync(f, 'utf8'));
    out.push(b.s); styles.push(b.style || 'classic');
  }
  const file = `// way-out/js/boards10.js - GENERATED by tools/build-arrow-boards10.mjs (2026-10-28). NEVER HAND-EDIT.
// Arrow Maze's Expert boards on generator 10 (${W}x${H}, packed; engine.js unpackB10 / buildB10).
// APPEND-ONLY once shipped: a level number names its board (way-out/js/test.js pins it).
export const B10_W = ${W};
export const B10_H = ${H};
export const B10 = ${JSON.stringify(out)};
// Each board's style (tools/arrow-styles.mjs): classic, curly, long, or pairs (two arrows free at some steps).
export const B10_STYLE = ${JSON.stringify(styles)};
`;
  writeFileSync(new URL('../way-out/js/boards10.js', import.meta.url), file);
  console.log(`wrote way-out/js/boards10.js (${out.length} boards, ${(file.length / 1024).toFixed(1)} KB)`);
} else {
  mkdirSync(PARTS_DIR, { recursive: true });
  const part = arg('--part', 0), parts = arg('--parts', 1);
  for (let k = part; k < COUNT; k += parts) {
    const f = new URL(`b${k}.json`, PARTS_DIR);
    if (existsSync(f)) continue;   // resumable
    const t0 = Date.now();
    const b = boardAt(k);
    writeFileSync(f, JSON.stringify(b));
    console.log(`board ${k}${b.style ? ' ' + b.style : ''}: ${b.m.n} arrows, jump ${b.m.jump}, blocker ${b.m.dist} (${Math.round((Date.now() - t0) / 1000)} s)`);
  }
}
