// tools/build-arrow-boards12.mjs - GENERATES way-out/js/boards12.js: Arrow Maze's Easy from 51 and Medium from 101
// on GENERATOR 12 (2026-11-02). Matt played the Easy / Medium test boards (tools/build-arrow-easymed-tests.mjs):
// "I like these better. We can keep like idk 50 or 100 of the existing easy ones, then put these after. Same with
// medium", then "Build it". His picks, the recipes that came closest to ~2 points a minute:
//   Easy   = Easy test 3:   12x16, ~22 arrows, one or two arrows free at a time, blockers ~5 dots away (his 0:23);
//   Medium = Medium test 1: 16x22, ~45 arrows, generator 8's old Hard style, two or three free (his 0:46).
// Packed as generator 10's (11 bits a cell), read by engine.js unpackB10 / buildB12.
//   node tools/build-arrow-boards12.mjs [--count 100]
// APPEND-ONLY once shipped (way-out/js/test.js pins it): a level number names its board. Re-running keeps every
// board already in the file and only adds new ones.
import { writeFileSync } from 'node:fs';
import { measure, search, setGrid } from './arrow-search.mjs';
const E = await import('../way-out/js/engine.js');
const arg = (k, d) => (process.argv.includes(k) ? +process.argv[process.argv.indexOf(k) + 1] : d);
const COUNT = arg('--count', 100);

// The test boards' recipes, exactly (tools/build-arrow-easymed-tests.mjs boards 3 and 4).
const BANDS = {
  easy: { W: 12, H: 16, style: 'hard', over: { minN: 22, maxN: 26, fill: 0.5, free0: 3, free: 0.6, dist: 3, farS: 6, maxR: 18, keep: 20 },
    ok: (m) => m.n >= 21 && m.n <= 27 && m.avgFree >= 1.15 && m.avgFree <= 1.7 },
  medium: { W: 16, H: 22, style: 'hard', over: {},
    ok: (m) => m.n >= 42 && m.maxFree <= 4 },
};

function pack(arrows, W) {
  const STEP = { 1: 0, [-1]: 1, [W]: 2, [-W]: 3 };
  const bits = [];
  const put = (v, n) => { for (let k = n - 1; k >= 0; k--) bits.push((v >> k) & 1); };
  put(arrows.length, 7);
  for (const c of arrows) { put(c[0], 11); put(c.length - 1, 5); for (let k = 1; k < c.length; k++) put(STEP[c[k] - c[k - 1]], 2); }
  while (bits.length % 8) bits.push(0);
  const bytes = Buffer.alloc(bits.length / 8);
  for (let i = 0; i < bytes.length; i++) { let v = 0; for (let k = 0; k < 8; k++) v = (v << 1) | bits[i * 8 + k]; bytes[i] = v; }
  return bytes.toString('base64');
}

let shipped = { easy: [], medium: [] };
try { shipped = (await import('../way-out/js/boards12.js')).B12; } catch { /* first build */ }
const out = { easy: shipped.easy.slice(), medium: shipped.medium.slice() };
for (const band of ['easy', 'medium']) {
  const B = BANDS[band];
  setGrid(B.W, B.H);
  for (let k = out[band].length; k < COUNT; k++) {
    let kept = null;
    for (let s = 0; s < 30 && !kept; s++) {
      const a = search(E.seedOf(`b12-${band}-${k}`, s), B.style, 60000, B.over);
      const m = measure(a);
      if (m && B.ok(m) && a.every((c) => c.length <= 32)) kept = { a, m };
    }
    if (!kept) throw new Error(`${band} board ${k}: no seed met the recipe`);
    out[band].push(pack(kept.a, B.W));
    if (k % 10 === 9) console.log(`${band} ${k + 1}: ${kept.m.n} arrows, free avg ${kept.m.avgFree.toFixed(2)}, blockers ${kept.m.dist.toFixed(1)}`);
  }
}
const file = `// way-out/js/boards12.js - GENERATED by tools/build-arrow-boards12.mjs (2026-11-02). NEVER HAND-EDIT.
// Arrow Maze's Easy (from 51, 12x16) and Medium (from 101, 16x22) boards on generator 12, packed as generator 10's
// (engine.js unpackB10 / buildB12). APPEND-ONLY once shipped: a level number names its board (way-out/js/test.js).
export const B12_GRID = { easy: [12, 16], medium: [16, 22] };
export const B12 = ${JSON.stringify(out)};
`;
writeFileSync(new URL('../way-out/js/boards12.js', import.meta.url), file);
console.log(`wrote way-out/js/boards12.js (Easy ${out.easy.length}, Medium ${out.medium.length}; ${(file.length / 1024).toFixed(1)} KB)`);
