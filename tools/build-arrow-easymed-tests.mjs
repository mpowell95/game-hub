// tools/build-arrow-easymed-tests.mjs - GENERATES way-out/js/easymed-tests.js: Arrow Maze's EASY and MEDIUM
// test boards (2026-11-01, admin only). Matt, on points per minute (Easy and Medium pay ~3.3 a minute, Hard
// ~2, Expert ~1): "I think we're better off adjusting the difficulties of easy and medium instead", then "Make
// test boards". Targets (everyone's clean times): Easy ~0:30 a level (today ~0:18), Medium ~1:00 (today
// ~0:36), so both pay ~2 points a minute like Hard. Three recipes each, so Matt can say which kind he likes:
//   1  the old generator-8 Hard style (two or three arrows free, blockers a few dots away);
//   2  one arrow free at every step (generator 11's Hard, smaller);
//   3  in between: today's board size, fewer arrows free at a time.
// Each board is proved solvable by measure() (tools/arrow-search.mjs). APPEND-ONLY: Matt's results name
// the boards by number.
//
//   node tools/build-arrow-easymed-tests.mjs
import { writeFileSync } from 'node:fs';
import { measure, search, setGrid } from './arrow-search.mjs';
const E = await import('../way-out/js/engine.js');

let shipped = [];
try { shipped = (await import('../way-out/js/easymed-tests.js')).EM_TESTS; } catch { shipped = []; }

// tier, name, grid, style + overrides, and what a kept board must measure.
const PLAN = [
  { tier: 'easy', grid: [11, 14], style: 'hard', over: { minN: 20, maxN: 24, fill: 0.5, free0: 4, dist: 2, farS: 4, rounds: 0.3, free: 0.15, maxR: 11, keep: 18 },
    ok: (m) => m.n >= 19 && m.n <= 26 && m.avgFree >= 1.6 && m.maxFree <= 4 },
  { tier: 'easy', grid: [10, 13], style: 'jumps', over: { minN: 11, maxN: 13, fill: 0.35, keep: 9, jump: 4, near: 1 },
    ok: (m) => m.n >= 10 && m.n <= 14 && m.rounds === m.n && m.maxFree === 1 },
  { tier: 'easy', grid: [12, 16], style: 'hard', over: { minN: 22, maxN: 26, fill: 0.5, free0: 3, free: 0.6, dist: 3, farS: 6, maxR: 18, keep: 20 },
    ok: (m) => m.n >= 21 && m.n <= 27 && m.avgFree >= 1.15 && m.avgFree <= 1.7 },
  { tier: 'medium', grid: [16, 22], style: 'hard', over: {},
    ok: (m) => m.n >= 42 && m.maxFree <= 4 },
  { tier: 'medium', grid: [14, 19], style: 'jumps', over: { minN: 24, maxN: 28, fill: 0.45, keep: 20, jump: 6, near: 3 },
    ok: (m) => m.n >= 22 && m.rounds === m.n && m.maxFree === 1 },
  { tier: 'medium', grid: [15, 20], style: 'hard', over: { minN: 38, maxN: 42, fill: 0.55, free0: 2, free: 0.8, maxR: 30, keep: 34 },
    ok: (m) => m.n >= 36 && m.avgFree <= 1.6 },
];

const out = shipped.map((b) => ({ ...b }));
for (let i = out.length; i < PLAN.length; i++) {
  const P = PLAN[i];
  setGrid(P.grid[0], P.grid[1]);
  let kept = null;
  for (let k = 0; k < 20 && !kept; k++) {
    const t0 = Date.now();
    const a = search(E.seedOf(`easymed-${i}`, k), P.style, 60000, P.over);
    const m = measure(a);
    const good = m && P.ok(m);
    console.log(`${P.tier} test ${i + 1} seed ${k}: ${m.n} arrows, rounds ${m.rounds}, free avg ${m.avgFree.toFixed(1)} max ${m.maxFree}, start ${m.free0}, blockers ${m.dist.toFixed(1)}, jump ${m.jump.toFixed(1)} ${good ? 'KEPT' : 'thrown away'} (${Date.now() - t0} ms)`);
    if (good) kept = { tier: P.tier, grid: P.grid, arrows: a };
  }
  if (!kept) throw new Error(`no board for test ${i + 1}`);
  out.push(kept);
}

writeFileSync(new URL('../way-out/js/easymed-tests.js', import.meta.url),
  `// way-out/js/easymed-tests.js - GENERATED by tools/build-arrow-easymed-tests.mjs (2026-11-01). NEVER HAND-EDIT.\n`
  + `// Arrow Maze's EASY and MEDIUM test boards (admin only): { tier, grid: [cols, rows], arrows }.\n`
  + `export const EM_TESTS = ${JSON.stringify(out)};\n`);
console.log(`wrote ${out.length} boards`);
