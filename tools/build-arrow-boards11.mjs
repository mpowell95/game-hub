// tools/build-arrow-boards11.mjs - GENERATES way-out/js/boards11.js: Arrow Maze's Hard on GENERATOR 11
// (2026-10-28). Matt: "Now Hard is too easy ... make Hard a bit more challenging. Not as challenging as expert".
// Impossible test boards 7-8's recipe on their grid (18x25, between generator 8's 16x22 and Expert's 28x38):
// exactly one arrow free at every step, the next one ~6-8 dots from the last, no trains, ~45-60 arrows
// (Expert: ~75-80 on 28x38). Parallel parts, as tools/build-arrow-boards10.mjs:
//   node tools/build-arrow-boards11.mjs --part <k> --parts <N> --count <C>   (writes a part file)
//   node tools/build-arrow-boards11.mjs --merge --count <C>                  (writes boards11.js)
// APPEND-ONLY once shipped (way-out/js/test.js pins it): a level number names its board.
import { writeFileSync, readFileSync, existsSync, mkdirSync } from 'node:fs';
import { measure, search, setGrid } from './arrow-search.mjs';
const E = await import('../way-out/js/engine.js');
const arg = (k, d) => (process.argv.includes(k) ? +process.argv[process.argv.indexOf(k) + 1] : d);
const W = 18, H = 25, COUNT = arg('--count', 100), ITERS = arg('--iters', 300000);
const OVER = { jump: 18, near: 8, minN: 55, maxN: 75, fill: 0.58, rounds: 4, dist: 7, farS: 30 };   // boards 7-8's
const PARTS_DIR = new URL('../.boards11-parts/', import.meta.url);

// Packing (generator 10's, so one reader serves both): 7 bits arrow count; per arrow 11 bits tail cell, 5 bits (length - 1),
// then 2 bits a step (0 right, 1 left, 2 down, 3 up), tail to head. Base64. engine.js unpackB10 reads it.
const STEP = { 1: 0, [-1]: 1, [W]: 2, [-W]: 3 };
function pack(arrows) {
  const bits = [];
  const put = (v, n) => { for (let k = n - 1; k >= 0; k--) bits.push((v >> k) & 1); };
  put(arrows.length, 7);
  for (const c of arrows) { put(c[0], 11); put(c.length - 1, 5); for (let k = 1; k < c.length; k++) put(STEP[c[k] - c[k - 1]], 2); }
  while (bits.length % 8) bits.push(0);
  const bytes = Buffer.alloc(bits.length / 8);
  for (let i = 0; i < bytes.length; i++) { let v = 0; for (let k = 0; k < 8; k++) v = (v << 1) | bits[i * 8 + k]; bytes[i] = v; }
  return bytes.toString('base64');
}

/** Board k: the first seed whose search meets the recipe. */
function boardAt(k) {
  setGrid(W, H);
  for (let s = 0; s < 12; s++) {
    const a = search(E.seedOf(`b11-hard-${k}`, s), 'jumps', ITERS, OVER);
    const m = measure(a);
    if (m && m.n >= 44 && m.n <= 127 && m.rounds === m.n && m.maxFree === 1 && m.trains === 0 && m.jump >= 6.3 && a.every((c) => c.length <= 32)) {
      return { s: pack(a), m: { n: m.n, jump: +m.jump.toFixed(2), dist: +m.dist.toFixed(2) } };
    }
  }
  throw new Error(`board ${k}: no seed met the recipe`);
}

if (process.argv.includes('--merge')) {
  const out = [];
  for (let k = 0; k < COUNT; k++) {
    const f = new URL(`b${k}.json`, PARTS_DIR);
    if (!existsSync(f)) throw new Error(`missing part for board ${k}`);
    out.push(JSON.parse(readFileSync(f, 'utf8')).s);
  }
  const file = `// way-out/js/boards11.js - GENERATED by tools/build-arrow-boards11.mjs (2026-10-28). NEVER HAND-EDIT.
// Arrow Maze's Hard boards on generator 11 (${W}x${H}, packed as generator 10's; engine.js unpackB10 / buildB11).
// APPEND-ONLY once shipped: a level number names its board (way-out/js/test.js pins it).
export const B11_W = ${W};
export const B11_H = ${H};
export const B11 = ${JSON.stringify(out)};
`;
  writeFileSync(new URL('../way-out/js/boards11.js', import.meta.url), file);
  console.log(`wrote way-out/js/boards11.js (${out.length} boards, ${(file.length / 1024).toFixed(1)} KB)`);
} else {
  mkdirSync(PARTS_DIR, { recursive: true });
  const part = arg('--part', 0), parts = arg('--parts', 1);
  for (let k = part; k < COUNT; k += parts) {
    const f = new URL(`b${k}.json`, PARTS_DIR);
    if (existsSync(f)) continue;   // resumable
    const t0 = Date.now();
    const b = boardAt(k);
    writeFileSync(f, JSON.stringify(b));
    console.log(`board ${k}: ${b.m.n} arrows, jump ${b.m.jump}, blocker ${b.m.dist} (${Math.round((Date.now() - t0) / 1000)} s)`);
  }
}
