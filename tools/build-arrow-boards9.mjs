// tools/build-arrow-boards9.mjs - GENERATES way-out/js/boards9.js: Arrow Maze's Expert levels on GENERATOR 9
// (2026-10-27). Matt, a few hours into generator 8: "I feel like the test expert levels were much more
// difficult than the ones I'm doing rn". Measured: generator 8's Expert 201-260 were only the two milder
// test styles (far blockers, mixed; tests 1-7), the forced-order boards (tests 8-10) began at 261, and
// its 30-arrow far-blocker boards are barely harder than the new Hard. Generator 9 is FORCED ORDER (one
// arrow free at a time) four levels in five, the arrow count growing ~50 -> 70 over the first 100
// levels, with a MIXED board every fifth level; no far-blocker boards. Same search, same 16x22 grid.
// Generator 8's boards stay as shipped (levels already played or in progress keep them).
//
// APPEND-ONLY once shipped (way-out/js/test.js pins it). ~5 min.
//
//   node tools/build-arrow-boards9.mjs [--count 250] [--iters 20000]
import { writeFileSync } from 'node:fs';
import { W, H, measure, search } from './arrow-search.mjs';
const E = await import('../way-out/js/engine.js');
const arg = (k, d) => (process.argv.includes(k) ? +process.argv[process.argv.indexOf(k) + 1] : d);
const COUNT = arg('--count', 250), ITERS = arg('--iters', 20000);   // these defaults built the shipped file

/** Expert's k-th generator-9 board (0 = level 201): its style and arrow-count window. */
export function expertPlan(k) {
  if (k % 5 === 4) return { style: 'mixed' };
  const top = Math.round(52 + 18 * Math.min(1, k / 100));
  return { style: 'forced', over: { minN: top - 8, maxN: top } };
}

const STEP = { 1: 0, [-1]: 1, [W]: 2, [-W]: 3 };
function pack(arrows) {
  const bits = [];
  const put = (v, n) => { for (let k = n - 1; k >= 0; k--) bits.push((v >> k) & 1); };
  put(arrows.length, 7);
  for (const c of arrows) {
    put(c[0], 9); put(c.length - 1, 4);
    for (let k = 1; k < c.length; k++) put(STEP[c[k] - c[k - 1]], 2);
  }
  while (bits.length % 8) bits.push(0);
  const bytes = Buffer.alloc(bits.length / 8);
  for (let i = 0; i < bytes.length; i++) { let v = 0; for (let k = 0; k < 8; k++) v = (v << 1) | bits[i * 8 + k]; bytes[i] = v; }
  return bytes.toString('base64');
}

const out = [];
const t0 = Date.now();
let sum = { n: 0, rounds: 0 };
for (let k = 0; k < COUNT; k++) {
  const { style, over } = expertPlan(k);
  const arrows = search(E.seedOf('b9-expert', k), style, ITERS, over);
  if (arrows.length > 127 || arrows.some((c) => c.length > 16)) throw new Error('board too big to pack');
  const m = measure(arrows);
  sum.n += m.n; sum.rounds += m.rounds;
  const s = pack(arrows);
  if (JSON.stringify(E.unpackB8(s)) !== JSON.stringify(arrows)) throw new Error(`pack round trip failed: ${k}`);
  out.push(s);
  if ((k + 1) % 25 === 0) console.log(`expert ${k + 1}/${COUNT} (${((Date.now() - t0) / 1000).toFixed(0)} s)`);
}
console.log(`expert: ${COUNT} boards, avg ${(sum.n / COUNT).toFixed(0)} arrows, ${(sum.rounds / COUNT).toFixed(1)} rounds`);
const file = `// way-out/js/boards9.js - GENERATED by tools/build-arrow-boards9.mjs (2026-10-27). NEVER HAND-EDIT.
// Arrow Maze's Expert boards on generator 9 (${W}x${H}, packed like boards8.js; engine.js buildB9).
// APPEND-ONLY once shipped: a level number names its board (way-out/js/test.js pins it).
export const B9 = {
  expert: ${JSON.stringify(out)},
};
`;
writeFileSync(new URL('../way-out/js/boards9.js', import.meta.url), file);
console.log(`wrote way-out/js/boards9.js (${(file.length / 1024).toFixed(1)} KB)`);
